"""Emit native-edge/apppolicy/normcase_table.go: code points where Windows
ntpath.normcase (LCMapStringEx) differs from Go unicode.ToLower. Windows only,
and the table follows the Unicode version of the host that generates it."""
import ntpath
import platform
from pathlib import Path

rows = []
for cp in range(0x110000):
    if 0xd800 <= cp < 0xe000 or cp == 0x2f:
        continue
    c = chr(cp)
    n = ntpath.normcase(c)
    lower = c.lower()
    go = ord(lower) if len(lower) == 1 else cp
    if cp == 0x130:
        go = 0x69  # Go maps U+0130 to 'i'; Python's multi-char lower does not apply
    if len(n) == 1 and ord(n) != go:
        rows.append((cp, ord(n)))
lines = ['// Code generated by tools/generate_native_app_policy_normcase.py on %s; DO NOT EDIT.' % platform.platform(), '',
         'package apppolicy', '',
         '// normcaseOverride lists code points where Windows ntpath.normcase differs from unicode.ToLower.',
         'var normcaseOverride = map[rune]rune{']
lines += ['\t0x%x: 0x%x,' % row for row in rows]
lines += ['}', '']
Path(__file__).resolve().parents[1].joinpath('native-edge', 'apppolicy', 'normcase_table.go').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(len(rows))
