"""Emit native-edge/appevents/casefold_table.go from Python str.casefold.

Only code points whose casefold differs from themselves are listed (about
1.5k); Go's strings.ToLower is not the same function (e.g. U+00DF -> "ss").
The table follows the Unicode version of the Python that generates it."""
import sys
from pathlib import Path

B = chr(92)


def literal(text):
    return ''.join('%su%04x' % (B, ord(ch)) if ord(ch) < 0x10000 else '%sU%08x' % (B, ord(ch)) for ch in text)


rows = []
for cp in range(0x110000):
    if 0xd800 <= cp < 0xe000:
        continue
    c = chr(cp)
    f = c.casefold()
    if f != c:
        rows.append((cp, f))
out = ['// Code generated by tools/generate_native_casefold_table.py (Python %s, Unicode table of that build); DO NOT EDIT.' % sys.version.split()[0],
       '', 'package appevents', '', '// casefoldTable maps a code point to its str.casefold() expansion.', 'var casefoldTable = map[rune]string{']
for cp, f in rows:
    out.append('\t0x%x: "%s",' % (cp, literal(f)))
out += ['}', '']
target = Path(__file__).resolve().parents[1] / 'native-edge' / 'appevents' / 'casefold_table.go'
target.write_text('\n'.join(out), encoding='utf-8', newline='\n')
print(len(rows))
